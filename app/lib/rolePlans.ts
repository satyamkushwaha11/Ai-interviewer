import type { InterviewArea, InterviewPlan } from './types';

/**
 * Role-aware interview agendas.
 *
 * Every session walks an ordered list of competency areas rather than asking
 * scattered questions. A fullstack candidate gets language → frontend → backend
 * → database → API integration; an AI engineer or an HR candidate gets a
 * completely different flow.
 *
 * A per-candidate plan is normally generated from their resume (see
 * `buildPlanPrompt` + /api/summarize-profile). This library is the deterministic
 * fallback for when no AI provider is configured or the model returns garbage,
 * and it anchors what a good plan looks like for each role family.
 */

export const MIN_AREAS = 3;
export const MAX_AREAS = 6;

/** [key, title, focus, probes] — compact so the table below stays readable. */
type AreaSpec = [string, string, string, string[]];

function plan(roleFamily: string, specs: AreaSpec[]): InterviewPlan {
  return {
    roleFamily,
    areas: specs.map(([key, title, focus, probes]) => ({ key, title, focus, probes })),
  };
}

type RoleKey =
  // --- Engineering / build ---
  | 'fullstack' | 'frontend' | 'backend' | 'mobile-android' | 'mobile-ios'
  | 'embedded' | 'game-dev' | 'blockchain' | 'salesforce-developer'
  // --- Data / AI ---
  | 'ai-engineer' | 'data-scientist' | 'data-analyst' | 'data-engineer'
  | 'mlops' | 'computer-vision' | 'nlp' | 'bi-developer' | 'prompt-engineer'
  // --- Infrastructure / operations ---
  | 'devops' | 'sre' | 'cloud-architect' | 'platform-engineer'
  | 'network-engineer' | 'dba' | 'security'
  // --- Quality / architecture / leadership ---
  | 'qa-sdet' | 'solutions-architect' | 'engineering-manager'
  | 'technical-pm' | 'support-engineer' | 'ux-designer'
  // --- Non-technical ---
  | 'hr' | 'business-development' | 'sales' | 'product' | 'marketing'
  | 'finance' | 'support' | 'generic';

