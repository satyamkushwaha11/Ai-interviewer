/**
 * Pick a plan from the static library. The target role is the strongest signal;
 * resume and JD text act as weaker corroboration.
 */
export function detectRolePlan(input: {
  role?: string;
  jd?: string;
  resume?: string;
}): InterviewPlan {
  const roleText = ` ${(input.role ?? '').toLowerCase()} `;
  const bodyText = ` ${(input.jd ?? '').toLowerCase()} ${(input.resume ?? '').toLowerCase()} `;

  let best: { key: RoleKey; score: number } | null = null;

  for (const signal of SIGNALS) {
    const weight = signal.weight ?? 1;
    let score = 0;
    for (const term of signal.terms) {
      if (roleText.includes(term)) score += 10 * weight;
      else if (bodyText.includes(term)) score += weight;
    }
    if (score > 0 && (!best || score > best.score)) {
      best = { key: signal.key, score };
    }
  }

  return PLANS[best?.key ?? 'generic'];
}

/** Every plan in the library, for docs/tests. */
export function allRolePlans(): InterviewPlan[] {
  return Object.values(PLANS);
}

function cleanString(value: unknown, max: number): string {
  return typeof value === 'string' ? value.trim().slice(0, max) : '';
}

function slugify(value: string, fallback: string): string {
  const slug = value
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
  return slug || fallback;
}

/**
 * Validate a model-generated plan. Returns null when the shape is unusable so
 * the caller can fall back to the static library.
 */
export function normalizePlan(raw: unknown): InterviewPlan | null {
  if (!raw || typeof raw !== 'object') return null;
  const candidate = raw as { roleFamily?: unknown; areas?: unknown };
  if (!Array.isArray(candidate.areas)) return null;

  const seen = new Set<string>();
  const areas: InterviewArea[] = [];

  for (const item of candidate.areas) {
    if (!item || typeof item !== 'object') continue;
    const entry = item as { key?: unknown; title?: unknown; focus?: unknown; probes?: unknown };
    const title = cleanString(entry.title, 40);
    const focus = cleanString(entry.focus, 400);
    if (!title || !focus) continue;

    const key = slugify(cleanString(entry.key, 40) || title, `area-${areas.length + 1}`);
    if (seen.has(key)) continue;
    seen.add(key);

    const probes = Array.isArray(entry.probes)
      ? entry.probes.map((p) => cleanString(p, 200)).filter(Boolean).slice(0, 4)
      : undefined;

    areas.push({ key, title, focus, ...(probes?.length ? { probes } : {}) });
    if (areas.length === MAX_AREAS) break;
  }

  if (areas.length < MIN_AREAS) return null;

  return {
    roleFamily: cleanString(candidate.roleFamily, 60) || 'General',
    areas,
  };
}
